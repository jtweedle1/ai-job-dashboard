// Builds a Tabler icon font holding only the icons the app uses.
//
// The full webfont is ~500 KB of font plus ~200 KB of CSS for ~6,000 icons; we use a few dozen.
// This scans the source for `ti-*` class names, subsets the pinned @tabler/icons-webfont package
// down to those glyphs, and writes a small font + stylesheet that app/layout.tsx imports.
// Runs automatically before `npm run dev` and `npm run build`; run `npm run icons` after adding
// an icon while the dev server is already running.

import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIRS = ["app", "components", "lib", "types"];
const OUT_DIR = path.join(root, "styles", "icons");

const pkgDir = path.dirname(require.resolve("@tabler/icons-webfont/package.json"));
const { version } = JSON.parse(await readFile(path.join(pkgDir, "package.json"), "utf8"));
const tablerCss = await readFile(path.join(pkgDir, "dist", "tabler-icons.css"), "utf8");
const tablerFont = await readFile(path.join(pkgDir, "dist", "fonts", "tabler-icons.woff2"));

// Every icon Tabler ships: name → codepoint.
const glyphs = new Map();
for (const m of tablerCss.matchAll(/\.ti-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"/g)) {
  glyphs.set(m[1], parseInt(m[2], 16));
}

async function* sourceFiles(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* sourceFiles(full);
    else if (/\.(tsx?|jsx?)$/.test(entry.name)) yield full;
  }
}

// Icon names appear as literals ("ti-target", `ti ti-x`), never built from parts.
const used = new Set();
const unknown = new Set();
for (const dir of SOURCE_DIRS) {
  for await (const file of sourceFiles(path.join(root, dir))) {
    const text = await readFile(file, "utf8");
    for (const m of text.matchAll(/(?<![\w-])ti-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) {
      if (glyphs.has(m[1])) used.add(m[1]);
      else unknown.add(m[1]);
    }
  }
}

const names = [...used].sort();
const font = await subsetFont(tablerFont, names.map((n) => String.fromCodePoint(glyphs.get(n))).join(""), {
  targetFormat: "woff2",
});

const css = `/*!
 * Tabler Icons ${version} by tabler - https://tabler.io (MIT)
 * License - https://github.com/tabler/tabler-icons/blob/main/LICENSE
 * Generated by scripts/build-icons.mjs from the icons used in this app. Do not edit by hand.
 */
@font-face {
  font-family: "tabler-icons";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url("./tabler-icons.woff2") format("woff2");
}

.ti {
  font-family: "tabler-icons" !important;
  speak: none;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${names.map((n) => `.ti-${n}:before { content: "\\${glyphs.get(n).toString(16)}"; }`).join("\n")}
`;

await mkdir(OUT_DIR, { recursive: true });
await writeFile(path.join(OUT_DIR, "tabler-icons.woff2"), font);
await writeFile(path.join(OUT_DIR, "tabler-icons.css"), css);

console.log(`icons: ${names.length} Tabler ${version} glyphs, ${(font.length / 1024).toFixed(1)} KB font`);
if (unknown.size) console.warn(`icons: not in Tabler ${version}, so they won't render: ${[...unknown].sort().join(", ")}`);
